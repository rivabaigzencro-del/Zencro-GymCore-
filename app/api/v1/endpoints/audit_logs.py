"""Audit Log Read-Only Endpoints for GYMCORE.

Provides immutable, append-only security logs for compliance and management oversight.
Restricted strictly to OWNER and MANAGER roles.
NO POST, PUT, PATCH, or DELETE methods are implemented to preserve audit trail integrity.
"""
from datetime import date
from typing import Optional
from uuid import UUID

from fastapi import APIRouter, Depends, Query
from sqlalchemy.orm import Session

from app.core.auth import require_role
from app.core.database import get_db
from app.models.user import User, UserRole
from app.schemas.audit_logs import AuditLogListResponse, AuditLogResponse
from app.services import audit_service

router = APIRouter()

_VIEW_ROLES = (UserRole.OWNER, UserRole.MANAGER)


@router.get(
    "",
    response_model=AuditLogListResponse,
    summary="List Audit Logs",
    description="Query chronological append-only audit trail logs with filtering and pagination. Requires OWNER or MANAGER.",
)
async def list_audit_logs(
    start_date: Optional[date] = Query(None, description="Filter logs on or after this date"),
    end_date: Optional[date] = Query(None, description="Filter logs on or before this date"),
    user_id: Optional[UUID] = Query(None, description="Filter logs generated by specific user"),
    action: Optional[str] = Query(None, description="Filter logs by exact action string"),
    resource_type: Optional[str] = Query(None, description="Filter logs by resource type (e.g. USER, PAYMENT)"),
    resource_id: Optional[str] = Query(None, description="Filter logs by target resource identifier"),
    page: int = Query(1, ge=1, description="Page number"),
    page_size: int = Query(20, ge=1, le=100, description="Items per page"),
    db: Session = Depends(get_db),
    current_user: User = Depends(require_role(*_VIEW_ROLES)),
) -> AuditLogListResponse:
    res = audit_service.list_audit_logs(
        db=db,
        tenant_id=current_user.tenant_id,
        start_date=start_date,
        end_date=end_date,
        user_id=user_id,
        action=action,
        resource_type=resource_type,
        resource_id=resource_id,
        page=page,
        page_size=page_size,
    )
    return AuditLogListResponse(
        items=[AuditLogResponse.model_validate(log) for log in res["items"]],
        total=res["total"],
        page=res["page"],
        page_size=res["page_size"],
        pages=res["pages"],
    )


@router.get(
    "/{audit_id}",
    response_model=AuditLogResponse,
    summary="Get Audit Log Entry",
    description="Retrieve details of a specific audit log record. Requires OWNER or MANAGER.",
)
async def get_audit_log(
    audit_id: UUID,
    db: Session = Depends(get_db),
    current_user: User = Depends(require_role(*_VIEW_ROLES)),
) -> AuditLogResponse:
    log_data = audit_service.get_audit_log_or_404(
        db=db,
        tenant_id=current_user.tenant_id,
        audit_log_id=audit_id,
    )
    return AuditLogResponse.model_validate(log_data)

